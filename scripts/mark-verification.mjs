#!/usr/bin/env node

const allowedStatuses = new Set(['unverified', 'spot_checked', 'verified'])

function usage() {
  return [
    'Usage: node scripts/mark-verification.mjs <sutra-id> <status> [--out out/verification-<id>.sql]',
    '',
    'status: unverified | spot_checked | verified',
    'The generated SQL must be reviewed, then executed with wrangler d1 execute.',
  ].join('\n')
}

function parseArgs(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(usage())
    process.exit(0)
  }

  const positional = []
  let outFile
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--out') {
      outFile = argv[index + 1]
      if (!outFile) throw new Error('--out requires a file path')
      index += 1
    } else if (argv[index].startsWith('--')) {
      throw new Error(`Unknown option: ${argv[index]}`)
    } else {
      positional.push(argv[index])
    }
  }

  if (positional.length !== 2) throw new Error(usage())
  const [id, status] = positional
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,127}$/.test(id)) {
    throw new Error('sutra-id contains unsupported characters')
  }
  if (!allowedStatuses.has(status)) throw new Error(`Invalid status: ${status}`)
  return { id, status, outFile }
}

function quote(value) {
  return `'${value.replaceAll("'", "''")}'`
}

async function main() {
  const { mkdir, writeFile } = await import('node:fs/promises')
  const { dirname, resolve } = await import('node:path')
  const { id, status, outFile } = parseArgs(process.argv.slice(2))
  const outputPath = resolve(process.cwd(), outFile ?? `out/verification-${id}.sql`)
  const sql = [
    '-- Generated by scripts/mark-verification.mjs',
    '-- Only use verified after a complete human review.',
    `UPDATE sutras SET source_verification = ${quote(status)} WHERE id = ${quote(id)};`,
    `SELECT id, title_zh, source_verification, source_batch FROM sutras WHERE id = ${quote(id)};`,
    '',
  ].join('\n')

  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, sql, 'utf8')
  console.log(`Wrote ${outputPath}`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
})
